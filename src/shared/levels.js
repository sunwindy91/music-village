// 音高 → 颜色（彩虹梯度：低音冷色蓝 → 高音暖色金橙）
// 视觉上强化"高=上"：越高越暖越亮
function noteColor(midi) {
  const hue = 210 - (midi - 60) * 12;   // 60→210(蓝)  70→90(绿黄)  76→18(橙红)
  return 'hsl(' + hue + ', 85%, 65%)';
}

